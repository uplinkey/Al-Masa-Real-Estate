import React, { useState, useEffect } from 'react';
import { 
  MapPin, Search, Compass, CheckCircle2, AlertTriangle, 
  ExternalLink, Sparkles, RefreshCw, Layers, ShieldCheck, 
  Eye, Edit3, X, School, Stethoscope, ShoppingBag, Bus, Trees, Landmark
} from 'lucide-react';
import { Property, PropertyLocationIntelligence, NearbyPlace } from '../types';
import { api } from '../services/api';

interface LocationIntelligenceModalProps {
  isOpen: boolean;
  onClose: () => void;
  property: Property;
  currentUser: { id: string; name: string; role: string };
  onSuccess?: () => void;
}

export const LocationIntelligenceModal: React.FC<LocationIntelligenceModalProps> = ({
  isOpen,
  onClose,
  property,
  currentUser,
  onSuccess,
}) => {
  const [intel, setIntel] = useState<PropertyLocationIntelligence | null>(null);
  const [places, setPlaces] = useState<NearbyPlace[]>([]);
  const [radiusMeters, setRadiusMeters] = useState(2000);
  const [isSearching, setIsSearching] = useState(false);
  const [isSaving, setIsSaving] = useState(false);
  const [editingDescription, setEditingDescription] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('الكل');

  const canApprove =
    currentUser.role === 'ADMIN' ||
    currentUser.role === 'SUPER_ADMIN' ||
    currentUser.role === 'EXECUTIVE_DIRECTOR' ||
    currentUser.role === 'DEPARTMENT_MANAGER';

  useEffect(() => {
    if (isOpen && property?.id) {
      loadIntelligence();
    }
  }, [isOpen, property?.id]);

  const loadIntelligence = async () => {
    try {
      const data = await api.getPropertyLocationIntelligence(property.id);
      if (data && data.status !== 'لم يتم البحث') {
        setIntel(data);
        setPlaces(data.places || []);
        setEditingDescription(data.finalApprovedDescriptionAr || data.reviewedDescriptionAr || data.autoGeneratedDescriptionAr || '');
        setRadiusMeters(data.searchRadiusMeters || 2000);
      } else {
        setIntel(null);
        setPlaces([]);
        setEditingDescription('');
      }
    } catch (err) {
      console.error('Error loading location intelligence:', err);
    }
  };

  const handleRunSearch = async () => {
    try {
      setIsSearching(true);
      const res = await api.searchPropertyLocationIntelligence(property.id, radiusMeters);
      setIntel(res);
      setPlaces(res.places || []);
      setEditingDescription(res.autoGeneratedDescriptionAr || '');
    } catch (err: any) {
      alert(err.message || 'فشل تشغيل التحليل الجغرافي');
    } finally {
      setIsSearching(false);
    }
  };

  const togglePlaceSelection = (placeId: string) => {
    setPlaces((prev) =>
      prev.map((p) => (p.id === placeId ? { ...p, selectedForPublishing: !p.selectedForPublishing } : p))
    );
  };

  const handleApprove = async (newStatus: 'معتمد' | 'بانتظار المراجعة' | 'تم تعديل الوصف') => {
    try {
      setIsSaving(true);
      await api.approvePropertyLocationIntelligence(property.id, {
        status: newStatus,
        reviewedDescriptionAr: editingDescription,
        finalApprovedDescriptionAr: newStatus === 'معتمد' ? editingDescription : undefined,
        places,
      });
      await loadIntelligence();
      if (onSuccess) onSuccess();
      if (newStatus === 'معتمد') {
        onClose();
      }
    } catch (err: any) {
      alert(err.message || 'فشل حفظ الاعتماد');
    } finally {
      setIsSaving(false);
    }
  };

  if (!isOpen) return null;

  const filteredPlaces = places.filter((p) => selectedCategory === 'الكل' || p.category === selectedCategory);

  const getCategoryIcon = (category: string) => {
    switch (category) {
      case 'تعليم':
        return <School className="w-4 h-4 text-amber-400" />;
      case 'صحة':
        return <Stethoscope className="w-4 h-4 text-rose-400" />;
      case 'تسوق':
        return <ShoppingBag className="w-4 h-4 text-indigo-400" />;
      case 'مواصلات':
        return <Bus className="w-4 h-4 text-cyan-400" />;
      case 'ترفيه':
        return <Trees className="w-4 h-4 text-emerald-400" />;
      default:
        return <Landmark className="w-4 h-4 text-slate-400" />;
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/70 backdrop-blur-xs flex items-center justify-center p-4 overflow-y-auto">
      <div className="bg-slate-900 border border-slate-700 rounded-2xl w-full max-w-4xl max-h-[92vh] flex flex-col overflow-hidden text-xs shadow-2xl animate-in fade-in zoom-in-95">
        
        {/* Header */}
        <div className="px-6 py-4 bg-slate-950 border-b border-slate-800 flex items-center justify-between shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-amber-500/10 text-amber-400 flex items-center justify-center">
              <Compass className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-bold text-white text-base">التحليل الجغرافي والخدمات المحيطة</h3>
                {intel && (
                  <span
                    className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${
                      intel.status === 'معتمد'
                        ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                        : 'bg-amber-500/20 text-amber-400 border border-amber-500/30'
                    }`}
                  >
                    {intel.status}
                  </span>
                )}
              </div>
              <p className="text-slate-400 text-[11px]">
                {property.title} ({property.code}) | {property.district}
              </p>
            </div>
          </div>
          <button onClick={onClose} className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 overflow-y-auto flex-1 space-y-6">
          
          {/* Coordinates & Search Setup */}
          <div className="bg-slate-800/40 p-4 rounded-xl border border-slate-800 flex flex-wrap items-center justify-between gap-4">
            <div className="flex items-center gap-4">
              <div>
                <span className="text-[10px] text-slate-400 block">إحداثيات الوحدة:</span>
                <span className="font-mono text-white font-bold">
                  {property.mapLat?.toFixed(4) || 'غير محدد'}, {property.mapLng?.toFixed(4) || 'غير محدد'}
                </span>
              </div>
              <div>
                <span className="text-[10px] text-slate-400 block">نطاق البحث الجغرافي:</span>
                <select
                  value={radiusMeters}
                  onChange={(e) => setRadiusMeters(Number(e.target.value))}
                  className="px-2.5 py-1 bg-slate-800 border border-slate-700 rounded-lg text-white text-xs"
                >
                  <option value={500}>500 متر (محيط مشي)</option>
                  <option value={1000}>1 كم (محيط مباشر)</option>
                  <option value={2000}>2 كم (المنطقة والحي)</option>
                  <option value={5000}>5 كم (المحاور والمدينة)</option>
                </select>
              </div>
            </div>

            <button
              onClick={handleRunSearch}
              disabled={isSearching}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-500 disabled:opacity-50 text-white rounded-xl font-bold flex items-center gap-2 transition-colors cursor-pointer shadow-sm"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${isSearching ? 'animate-spin' : ''}`} />
              <span>{intel ? 'إعادة استكشاف المعالم القريبة' : 'بدء البحث التلقائي عن الخدمات'}</span>
            </button>
          </div>

          {/* Places Results */}
          {places.length > 0 && (
            <div className="space-y-3">
              <div className="flex items-center justify-between flex-wrap gap-2">
                <div className="flex items-center gap-2">
                  <h4 className="font-bold text-white text-sm">المعالم والخدمات المكتشفة ({places.length})</h4>
                  <span className="text-slate-400 text-[11px]">
                    (المحدد للنشر: {places.filter((p) => p.selectedForPublishing).length})
                  </span>
                </div>

                {/* Categories Filter */}
                <div className="flex items-center gap-1 overflow-x-auto">
                  {['الكل', 'تعليم', 'صحة', 'تسوق', 'مواصلات', 'ترفيه', 'خدمات عامة'].map((cat) => (
                    <button
                      key={cat}
                      onClick={() => setSelectedCategory(cat)}
                      className={`px-2.5 py-1 rounded-lg text-[10px] font-bold transition-all cursor-pointer ${
                        selectedCategory === cat
                          ? 'bg-amber-500 text-slate-950'
                          : 'bg-slate-800 text-slate-400 hover:text-white'
                      }`}
                    >
                      {cat}
                    </button>
                  ))}
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-2.5 max-h-56 overflow-y-auto p-1">
                {filteredPlaces.map((place) => (
                  <div
                    key={place.id}
                    onClick={() => togglePlaceSelection(place.id)}
                    className={`p-3 rounded-xl border transition-all cursor-pointer flex items-start justify-between gap-2 ${
                      place.selectedForPublishing
                        ? 'bg-slate-800/80 border-amber-500/80 shadow-xs'
                        : 'bg-slate-900 border-slate-800 opacity-60 hover:opacity-100'
                    }`}
                  >
                    <div className="flex items-start gap-2.5">
                      <div className="mt-0.5">{getCategoryIcon(place.category)}</div>
                      <div>
                        <div className="font-bold text-white text-xs">{place.name}</div>
                        <div className="text-[10px] text-slate-400 flex items-center gap-2 mt-0.5">
                          <span>{place.type}</span>
                          <span>•</span>
                          <span className="text-amber-400 font-medium">{place.distanceFormatted}</span>
                        </div>
                        {place.address && <p className="text-[10px] text-slate-500 mt-0.5">{place.address}</p>}
                      </div>
                    </div>

                    <input
                      type="checkbox"
                      checked={place.selectedForPublishing}
                      onChange={() => togglePlaceSelection(place.id)}
                      className="mt-1 w-4 h-4 rounded text-amber-500 focus:ring-amber-500"
                    />
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Marketing Location Description */}
          {places.length > 0 && (
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <label className="font-bold text-white text-xs flex items-center gap-1.5">
                  <Sparkles className="w-3.5 h-3.5 text-amber-400" />
                  <span>الوصف التسويقي الجغرافي باللغة العربية (قابل للمراجعة والتعديل)</span>
                </label>
                <span className="text-[10px] text-slate-500">
                  تم التوليد آلياً بناءً على المعالم المعتمدة فقط دون مبالغة
                </span>
              </div>

              <textarea
                rows={5}
                value={editingDescription}
                onChange={(e) => setEditingDescription(e.target.value)}
                className="w-full p-3 bg-slate-800 border border-slate-700 rounded-xl text-white text-xs leading-relaxed focus:outline-none focus:ring-1 focus:ring-amber-500 resize-none font-sans"
                placeholder="اكتب أو عدل الوصف الجغرافي هنا..."
              />
            </div>
          )}
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-3 bg-slate-950 border-t border-slate-800 flex items-center justify-between shrink-0">
          <div className="text-[11px] text-slate-500 flex items-center gap-1">
            <ShieldCheck className="w-4 h-4 text-emerald-400" />
            <span>لن يظهر الوصف التسويقي في صفحة العقار العامة قبل الاعتماد النهائي.</span>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => handleApprove('تم تعديل الوصف')}
              disabled={isSaving || !places.length}
              className="px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-semibold transition-colors"
            >
              حفظ المسودة
            </button>

            {canApprove && (
              <button
                onClick={() => handleApprove('معتمد')}
                disabled={isSaving || !places.length}
                className="px-4 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg text-xs font-bold transition-colors flex items-center gap-1.5 shadow-xs"
              >
                <CheckCircle2 className="w-3.5 h-3.5" />
                <span>اعتماد ونشر في صفحة العقار</span>
              </button>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
